-- architecture-benchmark — canonical PostgreSQL schema (version 1)
--
-- This file is normative (see the build plan §2). Every app applies an
-- equivalent schema locally; the rig verifies equivalence against this file
-- via pg_indexes, constraints, and column definitions.
--
-- Conventions:
--   * BIGINT identity ids: fixtures insert explicit ids and then advance the
--     identity sequences (spec/seed-spec.md) so live inserts never collide.
--   * All timestamps are UTC timestamptz. Fixture rows use explicit
--     deterministic timestamps; no reliance on nondeterministic defaults.

CREATE TABLE users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  display_name text NOT NULL,
  -- No UNIQUE constraint: no documented query requires it, and every index
  -- is a measured cost shared by all variants (spec/contract.md).
  email text NOT NULL
);

CREATE TABLE projects (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  description text NOT NULL DEFAULT '',
  -- Not indexed: project lists are ordered by id ASC (spec/queries.md).
  created_at timestamptz NOT NULL
);

CREATE TABLE tasks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id bigint NOT NULL REFERENCES projects(id) ON DELETE RESTRICT,
  assignee_id bigint REFERENCES users(id) ON DELETE SET NULL,
  title text NOT NULL CHECK (char_length(title) BETWEEN 1 AND 200),
  description text NOT NULL DEFAULT '',
  status text NOT NULL CHECK (status IN ('todo', 'doing', 'done')),
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL
);

CREATE TABLE comments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id bigint NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  author_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  body text NOT NULL CHECK (char_length(body) BETWEEN 1 AND 1000),
  created_at timestamptz NOT NULL
);

CREATE INDEX tasks_project_created_id_idx
  ON tasks (project_id, created_at DESC, id DESC);
CREATE INDEX tasks_project_status_created_id_idx
  ON tasks (project_id, status, created_at DESC, id DESC);
CREATE INDEX comments_task_created_id_idx
  ON comments (task_id, created_at DESC, id DESC);
CREATE INDEX tasks_assignee_id_idx ON tasks (assignee_id);
CREATE INDEX comments_author_id_idx ON comments (author_id);
